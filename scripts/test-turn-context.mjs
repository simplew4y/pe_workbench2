import assert from 'node:assert/strict';
import { buildTurnContext, classifyQuestion, checkTurnTools } from '../lib/turn-context.mjs';
const cases = { assumption: '解释 assumption 毛利率假设', sensitivity: '敏感性 what if 提高10%', evidence: 'forecast 预测已验证吗', ticker: '有没有代码 Cover', threshold: '失效条件阈值 falsifier', correction: '更正后自查', dependency: 'capex 不进入估值吗' };
for (const [kind, question] of Object.entries(cases)) assert(classifyQuestion(question).includes(kind));
// Target/deviation questions get the matching hard constraints in the injected protocol.
assert(classifyQuestion('目标价较现价偏离这么多').includes('target'));
const targetContext = await buildTurnContext({ question: '目标价较现价偏离这么多', ledger: null });
assert.match(targetContext.content, /G\*.*缺口/);
assert.match(targetContext.content, /workbook_trace/);
assert.match(targetContext.content, /westock_query/);
assert.match(targetContext.content, /首句/);
const context = await buildTurnContext({ question: Object.values(cases).join(' '), now: new Date('2026-03-31T16:00:00Z'), ledger: { facts: [{id:'A1',value:65,unit:'%',period:'2026Q1'}], corrections:[{from:'旧值',to:'新值',note:'已核'}], open:['待核'] } });
assert.match(context.content, /2026-04-01.*星期三/);
assert.match(context.content, /Q2.*进行中/);
assert.match(context.content, /Q1.*已结束/);
assert.match(context.content, /A1.*65/);
assert.match(context.content, /新值/);
assert(!context.content.includes('旧值'));
assert([...context.content].length <= 16000);
const huge = await buildTurnContext({ question: Object.values(cases).join(' '), ledger:{facts:[{value:'长'.repeat(3000)}]} });
assert([...huge.content].length <= 16000);
const findings = (answer, calls=[], routes=['dependency']) => checkTurnTools({answer, toolCalls:calls, routes});
assert.equal(findings('capex 不进入估值。')[0].rule, 'missing_path_trace');
assert.equal(findings('没有路径。', [{name:'workbook_trace',args:{mode:'path'},success:false}]).length, 1);
assert.equal(findings('没有路径。', [{name:'workbook_trace',args:{mode:'path'},success:true}]).length, 0);
assert.equal(findings('尚未核验是否影响估值。').length, 0);
assert.equal(findings('目标价提高10%。', [], ['sensitivity'])[0].rule, 'missing_calc');
assert.equal(findings('目标价提高10%。', [{name:'calc',success:true}], ['sensitivity']).length, 0);
assert.equal(findings('模型记录毛利率65%。', [], ['assumption']).length, 0);
console.log('turn context passed');
const { mkdtemp, mkdir, writeFile, rm } = await import('node:fs/promises');
const { tmpdir } = await import('node:os');
const path = await import('node:path');
const { readLedger } = await import('../lib/turn-context.mjs');
const root = await mkdtemp(path.join(tmpdir(),'f4-context-'));
try {
  assert.equal(await readLedger(root,'missing'),null);
  assert.equal(await readLedger(root,'../outside'),null);
  await mkdir(path.join(root,'.pi','ledger'),{recursive:true});
  await writeFile(path.join(root,'.pi','ledger','s.json'),JSON.stringify({facts:[{id:'F1',value:'ledger-value'}]}));
  assert.match((await buildTurnContext({root,sessionId:'s'})).content,/ledger-value/);
  await writeFile(path.join(root,'.pi','ledger','bad.json'),'{');
  assert.equal(await readLedger(root,'bad'),null);
  const before = await buildTurnContext({now:new Date('2026-03-31T15:59:59Z')});
  assert.match(before.content,/2026-03-31 星期二/);
  assert.match(before.content,/2026Q1仍在进行中/);
  const jan = await buildTurnContext({now:new Date('2025-12-31T16:00:00Z')});
  assert.match(jan.content,/2025Q4已结束/);
} finally { await rm(root,{recursive:true,force:true}); }
assert.equal(checkTurnTools({routes:['sensitivity'],answer:'差额为20亿元。',toolCalls:[{name:'calc',success:false}]} )[0].rule,'missing_calc');
console.log('ledger and calendar boundaries passed');
